#!/usr/bin/env python3
"""Inventory normative wording without mistaking a text match for enforcement."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
WORDS = re.compile(r'\b(?:must|never|refus\w*)\b', re.I)
OUTPUT = 'docs/NORMATIVE-RULE-INVENTORY.md'


def inventory(root):
    paths = [root/'AGENTS.md', root/'docs/OPERATIONS.md', *sorted((root/'skills').glob('*/SKILL.md'))]
    rows = []
    for path in paths:
        text = path.read_text()
        for match in re.finditer(r'\S[\s\S]*?(?=\n\s*\n|\Z)', text):
            paragraph = match.group().strip()
            if not WORDS.search(paragraph):
                continue
            source = path.relative_to(root).as_posix()
            key = hashlib.sha256((source+'\0'+paragraph).encode()).hexdigest()[:20]
            rows.append({'id':key, 'source':source, 'line':text.count('\n',0,match.start())+1,
                         'text':paragraph})
    return rows


def render(root):
    rows = inventory(root)
    mappings = json.loads((root/'config/rule-enforcement.json').read_text())
    if mappings.get('version') != 1:
        raise ValueError('unknown enforcement mapping version')
    mapped = mappings['rules']
    if set(mapped) - {r['id'] for r in rows}:
        raise ValueError('stale enforcement mappings require review; do not silently move them')
    lines = ['# Normative rule inventory', '',
             'Generated by `python3 scripts/inventory-rules.py`. The checked sources are',
             '`AGENTS.md`, `docs/OPERATIONS.md` and every `skills/*/SKILL.md`.',
             'Every paragraph, list item or table block containing **must**, **never** or',
             '**refuse/refuses/refused** is retained verbatim, including wrapped sentences.',
             'This intentionally includes descriptive wording; it does not claim to find all',
             'imperatives expressed using other words. Links name current source lines.', '',
             '**Enforced** means the named check covers the complete listed statement within',
             'its stated scope. **Prose-only** means no single mechanical check establishes the',
             'whole statement; partial checks may be named. Neither a source-text match nor a',
             'passing unit fixture proves source truth or real-artifact acceptance.', '',
             'Mappings are reviewed in `config/rule-enforcement.json`; unknown/new wording',
             'defaults to prose-only. `--check` detects stale inventory or stale mappings.',
             'See [publication rule decisions](PUBLICATION-INVARIANTS.md) for contradictions',
             'resolved from existing operator instructions and remaining judgment boundaries.', '',
             f'Inventory: {len(rows)} source blocks; '+
             f"{sum(v['status']=='enforced' for v in mapped.values())} mapped as enforced.", '']
    for row in rows:
        item = mapped.get(row['id'], {'status':'prose-only',
                    'scope':'No complete mechanical enforcement identified; retain as an agent/operator obligation.'})
        if item['status'] not in ('enforced','prose-only') or not item.get('scope'):
            raise ValueError('invalid enforcement mapping '+row['id'])
        refs = item.get('checks',[])
        if item['status']=='enforced' and not refs:
            raise ValueError('enforced rule requires check references')
        for ref in refs:
            name = ref.split('#')[0]
            path = root/name
            if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(root.resolve()):
                raise ValueError('check reference missing or outside repository: '+ref)
        lines += [f"## {row['id']} — {item['status']}", '',
                  f"Source: [{row['source']}:{row['line']}](../{row['source']}#L{row['line']}).", '',
                  *['> '+line for line in row['text'].splitlines()], '', item['scope'], '']
        if refs:
            lines += ['Checks: '+', '.join(f'[`{r}`](../{r})' for r in refs)+'.', '']
    return '\n'.join(lines)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    try:
        text=render(ROOT); path=ROOT/OUTPUT
        if path.is_symlink(): raise ValueError('inventory output is a symlink')
        if args.check:
            if path.read_text()!=text: raise ValueError('normative inventory is stale; review mappings and regenerate')
        else: path.write_text(text)
        print(json.dumps({'ok':True,'blocks':len(inventory(ROOT)),'bytes':len(text.encode())}))
        return 0
    except (OSError,ValueError,TypeError,KeyError) as exc:
        print(json.dumps({'ok':False,'error':str(exc)})); return 1


if __name__=='__main__': raise SystemExit(main())
